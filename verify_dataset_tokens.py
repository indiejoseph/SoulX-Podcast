"""Sanity check: are the stored speech_tokens consistent with the audio?

Picks several samples from the dataset, decodes the audio bytes, runs
s3tokenizer on it, and compares the freshly-computed tokens against the
stored `speech_tokens` column.

Three possible outcomes:
  - PERFECT MATCH:    dataset is internally consistent. High training CE is
                      caused by speaker diversity / preference mismatch,
                      NOT a tokenizer mismatch.
  - PREFIX MATCH:     first N tokens agree but later diverge. Likely silence
                      trimming or padding difference. Mostly OK.
  - MAJOR DISAGREEMENT: stored tokens were generated by a different
                       tokenizer / different config / different preprocessing
                       than what we expect. THIS is the bug.
"""

from __future__ import annotations

import io
import sys
from pathlib import Path
from collections import Counter

import numpy as np
import torch
import torch.nn.functional as F
from datasets import Audio, load_from_disk


DATASET_PATH = "/notebooks/projects/SoulX-Podcast/tmp/dataset_small_with_tokens"


def decode_audio_bytes(audio_bytes: bytes):
    """Return (waveform[T], sample_rate) — mono float32."""
    import soundfile as sf
    with io.BytesIO(audio_bytes) as buf:
        wav, sr = sf.read(buf, dtype="float32", always_2d=False)
    if wav.ndim == 2:
        wav = wav.mean(axis=1)
    return wav, sr


@torch.inference_mode()
def tokenize_audio(s3model, audio_bytes: bytes, target_sr: int = 16000):
    """Decode bytes → 16kHz mono → s3tokenizer.quantize. Returns 0-based ids."""
    import s3tokenizer

    wav, src_sr = decode_audio_bytes(audio_bytes)

    if src_sr != target_sr:
        import torchaudio
        wav_t = torch.from_numpy(wav).unsqueeze(0)
        wav_t = torchaudio.functional.resample(
            wav_t, orig_freq=src_sr, new_freq=target_sr,
        )
        wav = wav_t.squeeze(0).numpy()

    # Match the inference-side volume normalize (utils/audio.py).
    from soulxpodcast.utils.audio import audio_volume_normalize
    audio = torch.from_numpy(wav).float()
    audio = audio_volume_normalize(audio)

    log_mel = s3tokenizer.log_mel_spectrogram(audio)        # [num_mels, T]
    mels, mel_lens = s3tokenizer.padding([log_mel])         # [1, num_mels, T'], [1]
    mels = mels.cuda()
    mel_lens = mel_lens.cuda()

    ids, lens = s3model.quantize(mels, mel_lens)            # [1, T''], [1]
    return ids[0, : int(lens[0].item())].cpu().tolist()


def compare_tokens(stored, fresh, label):
    """Pretty-print comparison between two token sequences."""
    n_stored = len(stored)
    n_fresh = len(fresh)
    print(f"  {label}: stored={n_stored} tokens, fresh={n_fresh} tokens")

    # Exact match
    if stored == fresh:
        print(f"    ✓ EXACT MATCH (all {n_stored} tokens identical)")
        return "exact"

    # Prefix match length
    common_len = min(n_stored, n_fresh)
    prefix_match = 0
    for i in range(common_len):
        if stored[i] == fresh[i]:
            prefix_match += 1
        else:
            break
    print(f"    prefix match: {prefix_match}/{common_len} ({prefix_match/max(common_len,1):.1%})")

    # Per-position match (regardless of prefix)
    pos_matches = sum(1 for a, b in zip(stored, fresh) if a == b)
    print(f"    per-position match: {pos_matches}/{common_len} ({pos_matches/max(common_len,1):.1%})")

    # Set overlap
    stored_set = set(stored[:200])
    fresh_set = set(fresh[:200])
    overlap = stored_set & fresh_set
    print(f"    vocab overlap (first 200): {len(overlap)} unique tokens shared")
    print(f"    stored unique: {len(stored_set)}  fresh unique: {len(fresh_set)}")

    # First divergence detail
    if prefix_match < common_len:
        i = prefix_match
        print(f"    first divergence at pos {i}: stored={stored[i]} vs fresh={fresh[i]}")
        # Show window around divergence
        a = max(0, i - 3)
        b = min(common_len, i + 4)
        print(f"      stored[{a}:{b}] = {stored[a:b]}")
        print(f"      fresh [{a}:{b}] = {fresh[a:b]}")

    # Distribution comparison
    stored_mean = float(np.mean(stored)) if stored else 0
    fresh_mean = float(np.mean(fresh)) if fresh else 0
    print(f"    stored token mean: {stored_mean:.1f}  fresh token mean: {fresh_mean:.1f}")

    # Classify
    pos_match_rate = pos_matches / max(common_len, 1)
    if pos_match_rate > 0.95:
        return "near_exact"
    if pos_match_rate > 0.5:
        return "partial"
    if len(overlap) > 50:
        return "same_vocab_different_seq"
    return "major_disagreement"


def main():
    import s3tokenizer

    print("=" * 72)
    print("DATASET TOKEN CONSISTENCY CHECK")
    print("=" * 72)

    print("\n[setup] loading s3tokenizer...")
    s3model = s3tokenizer.load_model("speech_tokenizer_v2_25hz").cuda().eval()

    print(f"[setup] loading dataset: {DATASET_PATH}")
    hf_ds = load_from_disk(DATASET_PATH)
    print(f"[setup] {len(hf_ds)} rows, columns: {hf_ds.column_names}")

    # Cast audio column to raw bytes (no torchcodec needed).
    hf_ds = hf_ds.cast_column("audio", Audio(decode=False))

    # Pick one sample per language for the check.
    samples_to_check = []
    for target_lang in ["en", "zh", "yue"]:
        for i in range(len(hf_ds)):
            if hf_ds[i]["lang"] == target_lang:
                samples_to_check.append((target_lang, i, hf_ds[i]))
                break

    verdicts = []
    for lang, idx, sample in samples_to_check:
        print()
        print("─" * 72)
        print(f"SAMPLE idx={idx} lang={lang}")
        print(f"  text: {sample['text'][:80]!r}{'...' if len(sample['text']) > 80 else ''}")
        print(f"  id: {sample.get('id', '?')}")
        print("─" * 72)

        # Stored tokens
        stored_str = sample["speech_tokens"]
        if isinstance(stored_str, str):
            stored = [int(x) for x in stored_str.split()]
        elif stored_str is None:
            print(f"  ⚠ no stored speech_tokens — skipping")
            continue
        else:
            stored = [int(x) for x in stored_str]

        # Re-tokenize audio
        audio_field = sample["audio"]
        if audio_field is None or "bytes" not in audio_field or audio_field["bytes"] is None:
            print(f"  ⚠ no audio bytes — skipping")
            continue
        audio_bytes = audio_field["bytes"]
        print(f"  audio: {len(audio_bytes)} bytes")

        try:
            fresh = tokenize_audio(s3model, audio_bytes)
        except Exception as e:
            print(f"  ✗ tokenization failed: {type(e).__name__}: {e}")
            continue

        verdict = compare_tokens(stored, fresh, f"lang={lang}")
        verdicts.append((lang, verdict))

    print()
    print("=" * 72)
    print("VERDICT")
    print("=" * 72)
    if not verdicts:
        print("  no comparisons made")
        return

    for lang, v in verdicts:
        print(f"  {lang}: {v}")
    print()

    classes = Counter(v for _, v in verdicts)
    if classes.get("exact", 0) == len(verdicts) or classes.get("near_exact", 0) == len(verdicts):
        print("  ✓ DATASET IS CONSISTENT. Stored tokens match s3tokenizer output.")
        print("    High training CE is from speaker diversity / preference mismatch,")
        print("    NOT a tokenizer bug. The data is fine.")
    elif classes.get("major_disagreement", 0) > 0:
        print("  ✗ MAJOR DISAGREEMENT in at least one language.")
        print("    Stored tokens look incompatible with s3tokenizer output —")
        print("    likely a different tokenizer or preprocessing was used. THIS")
        print("    would explain the high CE and means the dataset needs to be")
        print("    re-tokenized before training is meaningful.")
    elif classes.get("partial", 0) > 0:
        print("  ⚠ PARTIAL MATCH.")
        print("    Token sequences overlap heavily but aren't identical.")
        print("    Likely a minor preprocessing diff (silence trim, normalization).")
        print("    Probably fine for training but worth understanding.")
    else:
        print("  ⚠ INCONCLUSIVE — see per-sample output above.")


if __name__ == "__main__":
    main()
